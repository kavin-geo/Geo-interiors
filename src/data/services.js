import { siteAsset } from '../utils/siteAssets'

function createCategory({
  name,
  section,
  slug,
  stockPrefix = slug,
  projectImage,
  projectAlt,
  inspirationAlts,
}) {
  return {
    name,
    images: [
      { src: siteAsset(projectImage), alt: projectAlt },
      ...inspirationAlts.map((alt, index) => ({
        src: siteAsset(
          `gallery/${section}/${slug}/${stockPrefix}-${String(index + 2).padStart(2, '0')}.webp`,
        ),
        alt,
        inspiration: true,
      })),
    ],
  }
}

